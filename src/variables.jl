#=
Variable types for the noncommutative algebra system.
=#

export relation, ScaledFermion

#=
Creation and annihilation fermions with a scaling.
Generated by f_m and f_m^† satisfying
{f_m, f_n} = 0, {f_m, f_n^†} = δ_{m,n} * scaled_fermion_anticommutator(m).
The function scaled_fermion_anticommutator(m::Integer) must be defined by the calling code.
If scaled_fermion_anticommutator(m) = 1 then this code implements a standard fermion.
=#

struct ScaledFermion{R, S} <: AbstractVariable{R}
    label::S
    dagger::Bool # true => f^†, false => f
end

function scaled_fermion_anticommutator() end

# All dagger to the left, non-dagger to the right.
# Sort dagger increasing and non-dagger decreasing so that
# adjoint of a monomial is a monomial.
function relation(u1::ScaledFermion{R, S}, u2::ScaledFermion{R, S}) where {R, S}
    if u1 == u2
        return zero(Polynomial{R, ScaledFermion{R, S}})
    elseif (!u1.dagger) && u2.dagger
        if u1.label == u2.label
            return scaled_fermion_anticommutator(u1.label) - Monomial([u2, u1])
        else
            return -Monomial([u2, u1])
        end
    elseif u1.dagger == u2.dagger
        if u1.dagger && isless(u2.label, u1.label)
            return -Monomial([u2, u1])
        elseif (!u1.dagger) && isless(u1.label, u2.label)
            return -Monomial([u2, u1])
        end
    end
    return nothing
end

adjoint(u::ScaledFermion{R, S}) where {R, S} = ScaledFermion{R, S}(u.label, !u.dagger)
adjoint(m::Monomial{R, ScaledFermion{R, S}}) where {R, S} = Monomial(reverse(adjoint.(m.variables)))
